const rows = [];
const seen = new Set();
function add(group, keyword, intent, value, difficulty, firsthand) {
  if (seen.has(keyword)) return;
  seen.add(keyword);
  const score = intent * value * (6 - difficulty) * firsthand;
  rows.push({ group, keyword, intent, value, difficulty, firsthand, score });
}

for (const [role, firsthand, valueAdj] of roles) {
  for (const [group, mod, intent, value, difficulty] of roleModifiers) {
    add(group, `${role} ${mod}`, intent, Math.min(5, value + valueAdj), difficulty, firsthand);
  }
}
for (const r of [...standalone, ...roleSpecific]) add(...r);

rows.sort((a, b) => b.score - a.score || a.keyword.localeCompare(b.keyword, "ja"));

mkdirSync(join(root, "data"), { recursive: true });
const csv = [
  "group,keyword,intent,value,difficulty,firsthand,priority_score,volume",
  ...rows.map((r) => [r.group, r.keyword, r.intent, r.value, r.difficulty, r.firsthand, r.score, ""].join(",")),
].join("\n");
writeFileSync(join(root, "data", "keywords.csv"), csv + "\n");

